BOLD, DIM, RESET = "\033[1m", "\033[2m", "\033[0m"


def plain(text):
    """Strip the colour codes, for when output is not going to a terminal."""
    for code in (OK, MISSING, OPTIONAL, BOLD, DIM, RESET):
        text = text.replace(code, {OK: "OK", MISSING: "!!", OPTIONAL: "--"}.get(code, ""))
    return text


def say(text=""):
    print(text if sys.stdout.isatty() else plain(text))


def tilde(path):
    """Shorten a path under $HOME for display."""
    home = os.path.expanduser("~")
    if path == home or path.startswith(home + os.sep):
        return "~" + path[len(home):]
    return path


def human(size):
    for unit in ("B", "KB", "MB", "GB", "TB"):
        if size < 1024 or unit == "TB":
            return f"{size:.0f} {unit}" if unit == "B" else f"{size:.1f} {unit}"
        size /= 1024


# --- Where things go -------------------------------------------------------
@dataclass
class Install:
    """The layout of one installation, rooted at `root`.

    `app` is replaced wholesale by an upgrade; `venv` deliberately sits outside
    it so the dependencies survive one, and `manifest` marks the root as ours —
    --uninstall will not delete a directory that does not carry it.
    """

    root: str
    use_venv: bool = True
    # Set only by --no-venv: the interpreter to launch with instead.
    external_python: str = ""

    @property
    def app(self):
        return os.path.join(self.root, "app")

    @property
    def venv(self):
        return os.path.join(self.root, "venv")

    @property
    def manifest(self):
        return os.path.join(self.root, ".vertex-install.json")

    @property
    def entry_point(self):
        return os.path.join(self.app, "main.py")

    @property
    def python(self):
        """The interpreter the launcher will run the app with."""
        if not self.use_venv:
            return self.external_python or sys.executable
        return os.path.join(self.venv, "bin", "python")

    @property
    def installed(self):
        return os.path.exists(self.manifest)

    def read_manifest(self):
        try:
            with open(self.manifest) as handle:
                return json.load(handle)
        except (OSError, ValueError):
            return {}

    def logo(self, variant):
        """The desktop icon source, taken from the installed copy.

        The icon is scaled from artwork inside the install rather than out of
        the checkout, so the file the theme was built from is one that stays
        put.
        """
        return os.path.join(self.app, "Assets", "logo", variant,
                            f"{APP_ID}-mark-{variant}.png")


def base_python():
    """The interpreter to build the app's virtualenv from.

    When this script is itself running inside a virtualenv, that venv's python
    is a thin shim over a real installation; building from the real one keeps
    the app's environment independent of a checkout-local venv that may be
    deleted the moment the clone is.
    """
    candidate = getattr(sys, "_base_executable", "") or ""
    if candidate and os.path.isfile(candidate):
        return candidate
    return sys.executable


# --- Requirements ----------------------------------------------------------
@dataclass
class Requirement:
    """One thing the app needs, and how to obtain it on the running distro.

    Exactly one of `module`, `binary` or `library` says how to look for it:
    a Python module imported by a named interpreter, an executable on PATH, or
    a shared library the dynamic loader can find.
    """

    label: str
    module: str = ""
    binary: str = ""
    library: tuple = ()                            # candidate soname(s)
    required: bool = True
    note: str = ""                                 # what an optional one adds
    pip: str = ""                                  # pip distribution name
    system: dict = field(default_factory=dict)     # distro family -> package

    def check(self, python=None):
        """Returns (ok, detail) — detail explains a failure or names a version.

        `python` picks the interpreter a module is imported by. None means this
        one, which is what the pre-flight pass wants; the verification pass
        after the install passes the app's own interpreter, because a package
        installed for a *different* Python is exactly the failure this is meant
        to catch.
        """
        if self.module:
            if python and os.path.abspath(python) != os.path.abspath(sys.executable):
                return probe_module(python, self.module)
            try:
                mod = __import__(self.module)
            except ImportError as err:
                return False, str(err)
            except OSError as err:
                # python-mpv imports fine but loads libmpv at import time.
                return False, f"{type(err).__name__}: {err}"
            return True, str(getattr(mod, "__version__", ""))
        if self.library:
            return check_library(self.library)
        found = shutil.which(self.binary)
        return bool(found), found or f"{self.binary} not on PATH"


def probe_module(python, module):
    """Import `module` with another interpreter. Returns (ok, detail)."""
    code = ("import importlib, sys\n"
            "m = importlib.import_module(sys.argv[1])\n"
            "print(getattr(m, '__version__', ''))\n")
    try:
        done = subprocess.run([python, "-c", code, module],
                              capture_output=True, text=True, timeout=120)
    except (OSError, subprocess.SubprocessError) as err:
        return False, str(err)
    if done.returncode == 0:
        return True, done.stdout.strip()
    lines = [line for line in done.stderr.strip().splitlines() if line.strip()]
    return False, lines[-1] if lines else "import failed"


def check_library(sonames):
    """Look for a shared library the way python-mpv will at import time."""
    for soname in sonames:
        try:
            ctypes.CDLL(soname)
            return True, soname
        except OSError:
            continue
    found = ctypes.util.find_library(sonames[0].split(".so")[0].removeprefix("lib"))
    if found:
        return True, found
    return False, f"{sonames[0]} not found by the dynamic loader"


