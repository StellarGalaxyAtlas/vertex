#!/usr/bin/env python3
"""Installer for Vertex.

Copies the app to a permanent home, gives it a virtualenv of its own, and
registers it with the desktop so it appears in the start menu.

    ~/.local/lib/vertex/app/     the program — main.py, src/, Assets/
    ~/.local/lib/vertex/venv/    its dependencies, kept across upgrades
    ~/.local/bin/vertex          the launcher

The clone you run this from is only the source: once installed, the app no
longer reads anything out of it, so the checkout can be moved, updated or
deleted without breaking the start-menu entry. Re-run this script to upgrade
an existing install — only the `app/` folder is replaced, and it is swapped in
whole, so an interrupted upgrade leaves the previous version running.

**Nothing the user owns is ever written to.** Your config, your library, your
thumbnail cache, your clips and your exports are read to report on them and
otherwise left exactly as they are; an existing install is never asked to
migrate anything. Removing them is a separate, manual act, and --uninstall
prints the commands rather than running them.

    python install.py              install or upgrade, and add to the start menu
    python install.py --check      only report on the requirements
    python install.py --reset-config   re-run first-run setup on next launch
    python install.py --uninstall  remove the program, keeping all your data
"""

