def launcher_script(install):
    """A tiny shell wrapper, so the app is also a command in the terminal."""
    return f"""#!/bin/sh
{LAUNCHER_MARK}
exec {shell_quote(install.python)} {shell_quote(install.entry_point)} "$@"
"""


def desktop_entry(install):
    """The .desktop file contents.

    StartupWMClass must equal the WM_CLASS the window actually carries, or the
    running app shows up as a second, nameless taskbar icon. gui.App passes
    APP_ID to Tk as its className; Tk capitalizes that into the class half of
    WM_CLASS, which is what desktops match on.
    """
    wm_class = APP_ID.capitalize()
    return f"""[Desktop Entry]
Type=Application
Version=1.0
Name={APP_NAME}
GenericName=Clip Manager
Comment=Browse, trim and share your game clips
Exec={shell_quote(LAUNCHER)}
Path={install.app}
Icon={APP_ID}
Terminal=false
Categories=AudioVideo;Video;Recorder;
Keywords=clips;recording;gameplay;moments;replay;
StartupNotify=true
StartupWMClass={wm_class}
"""


def shell_quote(path):
    """Quote a path for a command line (spaces are the norm in home folders).

    A leading ~ is left outside the quotes, because inside them the shell
    hands the program a literal tilde instead of the home directory.
    """
    if " " not in path:
        return path
    if path.startswith("~/"):
        return f'~/"{path[2:]}"'
    return f'"{path}"'


def install_launcher(install):
    """Write ~/.local/bin/vertex. Returns False if it could not be written."""
    if os.path.exists(LAUNCHER):
        try:
            with open(LAUNCHER) as handle:
                ours = LAUNCHER_MARK in handle.read()
        except OSError:
            ours = False
        if not ours:
            # Somebody else's file under our name: theirs, so it stays.
            say(f"  {OPTIONAL} {tilde(LAUNCHER)} exists and is not ours — left "
                f"alone{RESET}")
            return True
    try:
        os.makedirs(BIN_DIR, exist_ok=True)
        with open(LAUNCHER, "w") as handle:
            handle.write(launcher_script(install))
        os.chmod(LAUNCHER, 0o755)
    except OSError as err:
        say(f"  {MISSING} {tilde(LAUNCHER)} {DIM}— {err}{RESET}")
        return False
    say(f"  {OK} launcher {DIM}{tilde(LAUNCHER)}{RESET}")
    if BIN_DIR not in os.environ.get("PATH", "").split(os.pathsep):
        say(f"  {OPTIONAL} {tilde(BIN_DIR)} is not on your PATH {DIM}— the start "
            f"menu entry works regardless{RESET}")
    return True


def install_icons(install, variant):
    """Write the logo into the hicolor icon theme at the usual sizes."""
    try:
        from PIL import Image
    except ImportError:
        # Pillow is in the app's venv rather than this interpreter; borrow it.
        return install_icons_via(install.python, install, variant)
    return scale_icons(Image, install.logo(variant))


def install_icons_via(python, install, variant):
    """Scale the icons with the app's own interpreter, which has Pillow."""
    code = (
        "import os, sys\n"
        "from PIL import Image\n"
        "logo, root, sizes = sys.argv[1], sys.argv[2], [int(s) for s in sys.argv[3:]]\n"
        "with Image.open(logo) as src:\n"
        "    src = src.convert('RGBA')\n"
        "    for size in sizes:\n"
        "        target = os.path.join(root, f'{size}x{size}', 'apps')\n"
        "        os.makedirs(target, exist_ok=True)\n"
        f"        src.resize((size, size), Image.LANCZOS).save(os.path.join(target, '{APP_ID}.png'))\n"
    )
    logo = install.logo(variant)
    if not os.path.exists(logo):
        say(f"  {MISSING} icons {DIM}— {tilde(logo)} not found{RESET}")
        return False
    try:
        done = subprocess.run(
            [python, "-c", code, logo, ICON_ROOT, *[str(s) for s in ICON_SIZES]],
            capture_output=True, text=True, timeout=300)
    except (OSError, subprocess.SubprocessError) as err:
        say(f"  {MISSING} icons {DIM}— {err}{RESET}")
        return False
    if done.returncode != 0:
        lines = done.stderr.strip().splitlines()
        say(f"  {MISSING} icons {DIM}— {lines[-1] if lines else 'failed'}{RESET}")
        return False
    say(f"  {OK} icons {DIM}{variant} artwork · {tilde(ICON_ROOT)}/<size>/apps/"
        f"{APP_ID}.png{RESET}")
    return True


def scale_icons(Image, logo):
    """Write every icon size from `logo` using an already-imported Pillow."""
    if not os.path.exists(logo):
        say(f"  {MISSING} icons {DIM}— {tilde(logo)} not found{RESET}")
        return False
    try:
        with Image.open(logo) as source:
            source = source.convert("RGBA")
            for size in ICON_SIZES:
                target_dir = os.path.join(ICON_ROOT, f"{size}x{size}", "apps")
                os.makedirs(target_dir, exist_ok=True)
                source.resize((size, size), Image.LANCZOS).save(
                    os.path.join(target_dir, f"{APP_ID}.png"))
    except (OSError, ValueError) as err:
        say(f"  {MISSING} icons {DIM}— {err}{RESET}")
        return False
    say(f"  {OK} icons {DIM}{tilde(ICON_ROOT)}/<size>/apps/{APP_ID}.png{RESET}")
    return True


def registered_files(app_id):
    """Every file the desktop integration writes for `app_id`."""
    return [os.path.join(DESKTOP_DIR, f"{app_id}.desktop")] + [
        os.path.join(ICON_ROOT, f"{size}x{size}", "apps", f"{app_id}.png")
        for size in ICON_SIZES
    ]


def remove_files(paths, complain=True):
    """Delete `paths`, ignoring the ones that were never there. Returns a count."""
    removed = 0
    for path in paths:
        try:
            os.remove(path)
            removed += 1
        except FileNotFoundError:
            pass
        except OSError as err:
            if complain:
                say(f"  {MISSING} {tilde(path)} {DIM}— {err}{RESET}")
    return removed


def remove_legacy_entries():
    """Drop the entries and icons left by the app's previous names."""
    paths = [path for app_id in LEGACY_APP_IDS
             for path in registered_files(app_id)]
    removed = remove_files(paths, complain=False)
    if removed:
        say(f"  {OK} removed {removed} file(s) {DIM}from an earlier name of the "
            f"app{RESET}")


def refresh_desktop_caches():
    """Nudge the desktop into noticing the entry. Best-effort and silent.

    kbuildsycoca is the one that matters on KDE: Plasma's launcher reads its own
    ksycoca cache, so an entry that update-desktop-database has already indexed
    still will not appear in the menu until this runs.
    """
    for argv in (["update-desktop-database", DESKTOP_DIR],
                 ["gtk-update-icon-cache", "-f", "-t", ICON_ROOT],
                 ["kbuildsycoca6", "--noincremental"],
                 ["kbuildsycoca5", "--noincremental"]):
        if shutil.which(argv[0]) is None:
            continue
        try:
            subprocess.run(argv, capture_output=True, timeout=60, check=False)
        except (OSError, subprocess.SubprocessError):
            pass


def install_desktop(install, variant):
    """Install the launcher, start-menu entry and icons. Returns False on failure."""
    say()
    say(f"{BOLD}Desktop integration{RESET}")

    ok = install_launcher(install)
    ok = install_icons(install, variant) and ok
    try:
        os.makedirs(DESKTOP_DIR, exist_ok=True)
        with open(DESKTOP_FILE, "w") as handle:
            handle.write(desktop_entry(install))
        os.chmod(DESKTOP_FILE, 0o755)
    except OSError as err:
        say(f"  {MISSING} {tilde(DESKTOP_FILE)} {DIM}— {err}{RESET}")
        return False
    say(f"  {OK} start menu entry {DIM}{tilde(DESKTOP_FILE)}{RESET}")
    say(f"  {OK} launches {DIM}{tilde(install.python)} "
        f"{tilde(install.entry_point)}{RESET}")

    remove_legacy_entries()
    refresh_desktop_caches()
    return ok


def uninstall(install):
    """Remove the program. Everything the user made is deliberately kept."""
    say(f"{BOLD}Removing {APP_NAME}{RESET}")

    paths = registered_files(APP_ID)
    for app_id in LEGACY_APP_IDS:
        paths += registered_files(app_id)
    say(f"  {OK} removed {remove_files(paths)} desktop file(s)")

    if os.path.exists(LAUNCHER):
        try:
            with open(LAUNCHER) as handle:
                ours = LAUNCHER_MARK in handle.read()
        except OSError:
            ours = False
        if ours:
            remove_files([LAUNCHER])
            say(f"  {OK} removed {DIM}{tilde(LAUNCHER)}{RESET}")
        else:
            say(f"  {OPTIONAL} {tilde(LAUNCHER)} is not ours — left alone")

    # The manifest is what proves this directory is an install of ours. Without
    # it we do not recursively delete anything.
    if install.installed:
        try:
            shutil.rmtree(install.root)
            say(f"  {OK} removed {DIM}{tilde(install.root)}{RESET}")
        except OSError as err:
            say(f"  {MISSING} {tilde(install.root)} {DIM}— {err}{RESET}")
    elif os.path.isdir(install.root):
        say(f"  {OPTIONAL} {tilde(install.root)} has no install marker — left "
            f"alone{RESET}")
    else:
        say(f"  {DIM}nothing installed at {tilde(install.root)}{RESET}")

    refresh_desktop_caches()

    say()
    say(f"{BOLD}Kept{RESET}")
    say(f"  {DIM}your clips, exports, config, library and thumbnails are "
        f"untouched.{RESET}")
    config = read_config()
    # Only the app's own bookkeeping is offered up for deletion. Clips and
    # exports are the user's own video files — printing an rm for those, next
    # to lines meant to be pasted, is how somebody loses a library.
    kept = [CONFIG_DIR] + [os.path.expanduser(config[key])
                           for key in ("data_path", "state_path", "cache_path")
                           if config.get(key)]
    removable = [path for path in dict.fromkeys(kept) if os.path.exists(path)]
    if removable:
        say(f"  {DIM}to also drop the library, settings and thumbnails:{RESET}")
        for path in removable:
            say(f"    {DIM}rm -r {shell_quote(tilde(path))}{RESET}")
    say(f"  {DIM}your clips and exports are not listed — deleting those is never "
        f"part of uninstalling{RESET}")


# --- Config ----------------------------------------------------------------
def reset_config():
    """Move the current config aside so the next launch runs setup again."""
    say(f"{BOLD}Config{RESET}")
    if not os.path.exists(CONFIG_PATH):
        say(f"  {OK} no config yet — the next launch runs setup")
        return
    # Stamped rather than a plain .bak, so resetting twice does not overwrite
    # the first backup — the one that has the settings worth getting back.
    backup = f"{CONFIG_PATH}.{time.strftime('%Y%m%d-%H%M%S')}.bak"
    try:
        os.replace(CONFIG_PATH, backup)
    except OSError as err:
        say(f"  {MISSING} could not move it aside {DIM}— {err}{RESET}")
        return
    say(f"  {OK} moved to {tilde(backup)} — the next launch runs setup")
    say(f"  {DIM}your library is untouched; setup will find it again if you "
        f"point it at the same folders{RESET}")


def ensure_dirs(config):
    """Make sure the folders the app will write into exist.

    An existing config names its own — often still under an older slug — and
    those are the ones created. Only a fresh install falls back to the XDG
    defaults. Existing folders are left exactly as they are.
    """
    say()
    say(f"{BOLD}Directories{RESET}")
    wanted = [CONFIG_DIR]
    if config:
        wanted += [os.path.expanduser(config[key]) for key in
                   ("data_path", "state_path", "cache_path") if config.get(key)]
    else:
        wanted += XDG_DIRS[1:]

    ok = True
    for path in dict.fromkeys(wanted):
        try:
            existed = os.path.isdir(path)
            os.makedirs(path, exist_ok=True)
            say(f"  {OK} {tilde(path)}" +
                (f" {DIM}(already there){RESET}" if existed else f" {DIM}(created){RESET}"))
        except OSError as err:
            ok = False
            say(f"  {MISSING} {tilde(path)} {DIM}— {err}{RESET}")
    return ok


def describe_first_run(install):
    """Show what the first-run screen will propose, without writing anything."""
    say()
    say(f"{BOLD}First launch{RESET}")
    say(f"  {DIM}Setup opens automatically and suggests these, derived from "
        f"your account:{RESET}")
    code = (
        "import sys\n"
        "sys.path.insert(0, sys.argv[1])\n"
        "import core\n"
        "d = core.default_config()\n"
        "print('\\n'.join(f'{k}\\t{getattr(d, k)}' for k in core.REQUIRED_FIELDS))\n"
    )
    try:
        done = subprocess.run([install.python, "-c", code,
                               os.path.join(install.app, "src")],
                              capture_output=True, text=True, timeout=120)
    except (OSError, subprocess.SubprocessError) as err:
        say(f"  {OPTIONAL} could not preview the defaults {DIM}— {err}{RESET}")
        return
    if done.returncode != 0:
        lines = done.stderr.strip().splitlines()
        say(f"  {OPTIONAL} could not preview the defaults {DIM}— "
            f"{lines[-1] if lines else 'failed'}{RESET}")
        return
    # Folders only: setup's later steps (audio devices, importing an existing
    # library) have nothing to derive from the account, so there is nothing to
    # preview for them here.
    for line in done.stdout.strip().splitlines():
        key, _, value = line.partition("\t")
        say(f"    {key:<12} {value}")


# --- Entry point -----------------------------------------------------------
def build_parser():
    parser = argparse.ArgumentParser(
        description=f"Install {APP_NAME} into a permanent location.")
    parser.add_argument("--check", action="store_true",
                        help="only report on the requirements, change nothing")
    parser.add_argument("--uninstall", action="store_true",
                        help="remove the program, keeping every file you made")
    parser.add_argument("--reset-config", action="store_true",
                        help="run first-run setup again on the next launch")
    parser.add_argument("--prefix", default=DEFAULT_PREFIX, metavar="DIR",
                        help=f"where to install (default: {tilde(DEFAULT_PREFIX)})")
    parser.add_argument("--no-venv", action="store_true",
                        help="use the interpreter running this script instead "
                             "of giving the app its own virtualenv")
    parser.add_argument("--recreate-venv", action="store_true",
                        help="rebuild the app's virtualenv from scratch")
    parser.add_argument("--no-desktop", action="store_true",
                        help="skip the launcher, start menu entry and icons")
    parser.add_argument("--icon", choices=("light", "dark"), default="light",
                        help="which ink the start-menu icon is drawn in: light "
                             "for a dark panel (the default), dark for a light "
                             "one")
    return parser


def main():
    args = build_parser().parse_args()

    install = Install(root=os.path.abspath(os.path.expanduser(
                          os.path.join(args.prefix, APP_ID))),
                      use_venv=not args.no_venv)

    say(f"{BOLD}{APP_NAME}{RESET}")
    say(f"  {DIM}source  {tilde(HERE)}{RESET}")
    say(f"  {DIM}install {tilde(install.root)}{RESET}")
    say()

    if args.uninstall:
        uninstall(install)
        return 0

    config = read_config()

    # Pre-flight: the version, then the things pip cannot supply.
    say(f"{BOLD}Interpreter{RESET}")
    py_ok = check_python()
    say()
    family = distro_family()
    missing_system, missing_optional = check_requirements(
        SYSTEM_REQUIREMENTS, heading="System requirements")
    report_fixes(missing_system + missing_optional, family)

    # Anything already installed is reported against the app's own interpreter,
    # since that is what a launch will use.
    if install.installed and os.path.exists(install.python):
        say()
        check_requirements(PIP_REQUIREMENTS, python=install.python,
                           heading="Python packages (installed)")
    else:
        say()
        say(f"{BOLD}Python packages{RESET}")
        for req in PIP_REQUIREMENTS:
            say(f"  {OPTIONAL} {req.pip} {DIM}— will be installed into the app's "
                f"virtualenv{RESET}")

    report_user_data(config)

    if args.check:
        say()
        if missing_system or not py_ok:
            say(f"{MISSING} Missing required components — see above.")
            return 1
        say("Nothing was changed (--check).")
        return 0

    if not py_ok or missing_system:
        say()
        say(f"{MISSING} {BOLD}Install the missing components above, then run "
            f"this again.{RESET}")
        return 1

    problem = guard_paths(install, config)
    if problem:
        say()
        say(f"{MISSING} {BOLD}Refusing to install:{RESET} {problem}.")
        say(f"  {DIM}pick somewhere else with --prefix DIR{RESET}")
        return 1

    absent = check_payload()
    if absent:
        say()
        say(f"{MISSING} {BOLD}The checkout is incomplete:{RESET} "
            f"{', '.join(absent)} not found in {tilde(HERE)}.")
        return 1

    if not install_payload(install):
        return 1

    if install.use_venv:
        if not build_venv(install, recreate=args.recreate_venv):
            return 1
        if not sync_dependencies(install):
            return 1
        say()
        missing_pip, _ = check_requirements(PIP_REQUIREMENTS, python=install.python,
                                            heading="Verifying")
        if missing_pip:
            say()
            say(f"{MISSING} {BOLD}The app's virtualenv is missing "
                f"{', '.join(req.label for req in missing_pip)}.{RESET}")
            return 1
    else:
        install.external_python = sys.executable
        if os.path.abspath(sys.executable).startswith(HERE + os.sep):
            say()
            say(f"{MISSING} {BOLD}--no-venv with an interpreter inside the "
                f"checkout.{RESET}")
            say(f"  {DIM}{tilde(sys.executable)} disappears with the clone, "
                f"which is the breakage this install is meant to avoid. Drop "
                f"--no-venv, or run this with a python from outside "
                f"{tilde(HERE)}.{RESET}")
            return 1
        say()
        missing_pip, _ = check_requirements(PIP_REQUIREMENTS, python=install.python,
                                            heading="Verifying")
        if missing_pip:
            say()
            say(f"{MISSING} {BOLD}Install these into {tilde(install.python)} "
                f"first:{RESET}")
            say(f"  {tilde(install.python)} -m pip install "
                f"{' '.join(req.pip for req in missing_pip)}")
            return 1

    write_manifest(install)

    ok = ensure_dirs(config)
    if args.reset_config:
        say()
        reset_config()
    if not args.no_desktop:
        ok = install_desktop(install, args.icon) and ok
    if not config:
        describe_first_run(install)

    say()
    if ok:
        how = (f"Look for “{APP_NAME}” in your start menu, or run: {APP_ID}"
               if not args.no_desktop else
               f"Run it with: {shell_quote(tilde(install.python))} "
               f"{shell_quote(tilde(install.entry_point))}")
        say(f"{OK} {BOLD}Installed.{RESET} {how}")
        say(f"  {DIM}The app runs from {tilde(install.app)} — the checkout at "
            f"{tilde(HERE)} is no longer needed.{RESET}")
        say(f"  {DIM}Pull an update and run this again to upgrade in place.{RESET}")
    else:
        say(f"{OPTIONAL} Finished with warnings — see above.")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
